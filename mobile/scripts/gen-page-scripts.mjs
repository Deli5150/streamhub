// Saves, as strings, the source of the code the app sends into web pages:
// - every function in the desktop's src/main/providers/pageScripts.ts (→ src/desktop/pageScripts.generated.ts)
// - the shared Twitch ad filter and the hooks that run it in the player page (→ src/player/twitchAdHook.generated.ts)
// The app would normally get these with fn.toString(), but Hermes compiles functions to bytecode, so
// toString() has no source in the app. Runs before every bundle (metro.config.js); `--check` fails if
// a saved copy is stale.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'
import ts from 'typescript'

const here = path.dirname(fileURLToPath(import.meta.url))
const check = process.argv.includes('--check')

/** CommonJS JavaScript for a TypeScript file. ES2022 runs in every WebView the app supports. */
const transpile = (file) =>
  ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, removeComments: true }
  }).outputText

/** The source of each exported function of a self-contained file. */
function functionSources(file) {
  const sandbox = { exports: {}, module: { exports: {} } }
  sandbox.module.exports = sandbox.exports
  vm.runInNewContext(transpile(file), sandbox)
  return Object.fromEntries(
    Object.entries(sandbox.module.exports)
      .filter(([, v]) => typeof v === 'function')
      .map(([name, fn]) => [name, fn.toString()])
  )
}

/** A whole module as one expression that evaluates to its exports. */
const moduleExpression = (file) => `(function () {\nvar exports = {};\n${transpile(file)}\nreturn exports;\n})()`

const outputs = [
  {
    file: path.resolve(here, '../src/desktop/pageScripts.generated.ts'),
    from: '../src/main/providers/pageScripts.ts',
    body: () => `export const PAGE_SCRIPT_SOURCES: Record<string, string> = ${JSON.stringify(functionSources(path.resolve(here, '../../src/main/providers/pageScripts.ts')), null, 2)}`
  },
  {
    file: path.resolve(here, '../src/player/twitchAdHook.generated.ts'),
    from: '../src/shared/twitchAdFilter.ts and src/player/twitchAdHook.ts',
    body: () =>
      [
        `export const TWITCH_AD_FILTER_LIB: string = ${JSON.stringify(moduleExpression(path.resolve(here, '../../src/shared/twitchAdFilter.ts')))}`,
        `export const TWITCH_AD_HOOK_SOURCES: Record<string, string> = ${JSON.stringify(functionSources(path.resolve(here, '../src/player/twitchAdHook.ts')), null, 2)}`
      ].join('\n')
  }
]

let stale = false
for (const out of outputs) {
  const text = `// Generated by scripts/gen-page-scripts.mjs from ${out.from}. Don't edit.\n${out.body()}\n`
  const current = fs.existsSync(out.file) ? fs.readFileSync(out.file, 'utf8') : ''
  if (current === text) continue
  if (check) {
    console.error(`${path.relative(process.cwd(), out.file)} is out of date; run \`npm run gen\``)
    stale = true
  } else {
    fs.writeFileSync(out.file, text)
    console.log(`updated ${path.relative(process.cwd(), out.file)}`)
  }
}
if (stale) process.exit(1)
