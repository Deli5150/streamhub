const get = async (name, variant) => {
  const res = await fetch(`https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/${name}/${variant}/24px.svg`)
  if (!res.ok) throw new Error(`${name}/${variant}: ${res.status}`)
  return (await res.text()).replace(/\s(height|width)="24"/g, '').trim()
}
const uri = (svg) => `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, '%27')}")`
const rules = []
const all = []
for (const [lucide, ms] of Object.entries(MAP)) {
  const [outline, filled] = await Promise.all([get(ms, 'default'), get(ms, 'fill1')])
  all.push(`svg.lucide-${lucide}`)
  rules.push(`:root[data-theme-style="pixel"] svg.lucide-${lucide} { --ms: ${uri(outline)}; --ms-on: ${uri(filled)}; }`)
}
const list = all.join(', ')
const css = `/*
 * Pixel colorways: the app's icons drawn as Material Symbols Rounded, the icon set of Android and
 * Pixel (Google, Apache 2.0). Each Lucide icon keeps its element (size, color, spin) but is painted
 * with the matching symbol as a mask; selected buttons get the filled symbol, as on Android.
 * Generated by scripts/pixel-icons.mjs — edit the mapping there, not this file.
 */
:root[data-theme-style="pixel"] :is(${list}) {
  background-color: currentColor;
  -webkit-mask: var(--ms) center / 100% 100% no-repeat;
  mask: var(--ms) center / 100% 100% no-repeat;
  stroke: none;
}
:root[data-theme-style="pixel"] :is(${list}) > * {
  display: none;
}
:root[data-theme-style="pixel"] :is([aria-pressed="true"], [aria-current="page"], [aria-selected="true"], [data-active="true"]) :is(${list}) {
  -webkit-mask-image: var(--ms-on);
  mask-image: var(--ms-on);
}
${rules.join('\n')}
`
fs.writeFileSync(process.argv[2], css)
console.log(`${Object.keys(MAP).length} icons, ${(css.length / 1024).toFixed(0)} KB`)
